export const menuItems: MenuItem[] = menuSectionCatalog.flatMap((section, sectionIndex) =>
  section.items.map(([name, prices], itemIndex) => {
    const priceList = [...prices] as number[];
    const sizeLabels =
      priceList.length >= 3
        ? ["Regular", "500 ML", "1 Liter"]
        : priceList.length === 2
          ? ["500 ML", "1 Liter"]
          : ["Regular"];

    return {
      id: sectionIndex * 100 + itemIndex + 1,
      name: name as string,
      category: section.category as string,
      emoji: section.emoji as string,
      description: section.description as string,
      badge: section.badge as string,
      sizes: priceList.map((price, sizeIndex) => ({
        label: sizeLabels[sizeIndex] ?? `Size ${sizeIndex + 1}`,
        price,
      })),
    };
  }),
);

export const menuCategories = ["All", ...new Set(menuItems.map((item) => item.category))];

